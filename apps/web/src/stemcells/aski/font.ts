export const FONT_W = 5,
  FONT_H = 7;

/** Edge cells use a density ramp; the inside of the body speaks in these. */
export const RAMP = " .:-=+*#%@";
export const BODY_CHARS = "aeioskxzr{}<>/=?*#";

const bits = new Map<string, Uint8Array>();
for (const [ch, rows] of Object.entries(GLYPHS)) {
  const flat = rows.replaceAll(" ", "");
  bits.set(
    ch,
    Uint8Array.from(flat, (c) => (c === "#" ? 1 : 0)),
  );
}

/** 1 where the glyph has ink at column `x` (0..4), row `y` (0..6). */
export function glyphBit(ch: string, x: number, y: number): number {
  const g = bits.get(ch);
  if (!g || x < 0 || y < 0 || x >= FONT_W || y >= FONT_H) return 0;
  return g[y * FONT_W + x]!;
}

export const hasGlyph = (ch: string): boolean => bits.has(ch);
